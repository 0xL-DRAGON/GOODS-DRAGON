    def check_bucket(self, bucket_name):
        urls = [
            f"https://{bucket_name}.s3.amazonaws.com",
            f"http://{bucket_name}.s3.amazonaws.com",
            f"https://{bucket_name}.s3.amazonaws.com/?list-type=2",
            f"https://s3.amazonaws.com/{bucket_name}"
        ]

        for url in urls:
            try:
                resp = requests.get(url, timeout=5, allow_redirects=False)
                # Check if bucket exists and is public
                if resp.status_code == 200:
                    # Check if it's an actual bucket listing
                    if 'ListBucketResult' in resp.text or '<Contents>' in resp.text or 'Bucket' in resp.text:
                        with self.lock:
                            self.found.append({
                                "bucket": bucket_name,
                                "url": url,
                                "status": "public_readable"
                            })
                            log_success(f"🔥 Found open S3 bucket: {bucket_name}")
                        return True
                    elif resp.status_code == 403:
                        # Bucket exists but private
                        if self.verbose:
                            log_debug(f"Bucket {bucket_name} exists but is private")
                    elif self.verbose:
                        log_debug(f"Bucket {bucket_name} -> {resp.status_code}")
            except Exception as e:
                if self.verbose:
                    log_debug(f"Error checking {bucket_name}: {e}")
        return False

    def run(self):
        log_info(f"Searching for S3 buckets related to: {self.target}")
        log_info(f"Checking {len(self.bucket_patterns)} bucket name patterns...")

        with ThreadPoolExecutor(max_workers=self.threads) as executor:
            futures = {executor.submit(self.check_bucket, name): name for name in self.bucket_patterns}
            for future in as_completed(futures):
                try:
                    future.result()
                except Exception as e:
                    log_error(f"Error: {e}")

        log_success(f"S3 scan completed. Found {len(self.found)} public buckets.")
        return {
            "target": self.target,
            "scan_type": "s3_finder",
            "total_found": len(self.found),
            "buckets": self.found
        }
